"""Export Blender objects to a Luau module that `Geo.model` rebuilds in Studio with no upload.

Run inside Blender (MCP `execute_blender_code`, or `blender --background file.blend --python ...`):

    import importlib.util
    spec = importlib.util.spec_from_file_location("geo_export", r"<plugin>/scripts/blender/geo_export.py")
    geo_export = importlib.util.module_from_spec(spec); spec.loader.exec_module(geo_export)
    print(geo_export.export(["Gate"], r"<project>/src/shared/Models/Gate.luau", name="Gate"))

Modifiers are applied. Each material becomes one MeshPart. Colours come from the active colour attribute,
else the material's Base Color. Set a custom property `rbx_material = "Metal"` on a material to choose the
Roblox material. Blender metres become studs through `scale`. Budget: about 6,000 triangles per module,
because each one is stored as text in a script.
"""
import base64
import struct

FORMAT = 1
MAX_VERTS = 65535


def _b64(data: bytes) -> str:
    return base64.b64encode(data).decode("ascii")


def _base_color(material):
    if material is None:
        return (0.8, 0.8, 0.8)
    if material.node_tree:
        for node in material.node_tree.nodes:
            if node.type == "BSDF_PRINCIPLED":
                return tuple(node.inputs["Base Color"].default_value[:3])
    return tuple(material.diffuse_color[:3])


def _srgb(value: float) -> int:
    value = max(0.0, min(1.0, value))
    value = value * 12.92 if value <= 0.0031308 else 1.055 * value ** (1 / 2.4) - 0.055
    return int(value * 255 + 0.5)


def _color_reader(mesh):
    attribute = mesh.color_attributes.active_color
    if attribute is None:
        return None
    data = attribute.data
    if attribute.domain == "CORNER":
        return lambda loop, vertex: data[loop].color
    return lambda loop, vertex: data[vertex].color


def pack(groups):
    """Pure. groups = {name: {"material": str, "corners": [(pos, normal, rgb), ...]}}, three corners a triangle."""
    bound = max((abs(c) for g in groups.values() for p, _, _ in g["corners"] for c in p), default=1.0) or 1.0
    unit = bound / 32767
    parts = []
    for name, group in groups.items():
        index = {}
        pos, nrm, col, tris = bytearray(), bytearray(), bytearray(), bytearray()
        for p, n, c in group["corners"]:
            q = tuple(int(round(v / unit)) for v in p)
            m = tuple(max(-127, min(127, int(round(v * 127)))) for v in n)
            key = (q, m, tuple(c))
            at = index.get(key)
            if at is None:
                at = index[key] = len(index)
                if at > MAX_VERTS:
                    raise ValueError(f"{name}: over {MAX_VERTS} vertices")
                pos += struct.pack("<hhh", *q)
                nrm += struct.pack("<bbb", *m)
                col += bytes(c)
            tris += struct.pack("<H", at)
        parts.append({
            "name": name, "material": group["material"], "verts": len(index), "tris": len(group["corners"]) // 3,
            "pos": _b64(pos), "nrm": _b64(nrm), "col": _b64(col), "idx": _b64(tris),
        })
    return {"format": FORMAT, "unit": unit, "parts": parts}


def to_luau(name: str, data: dict) -> str:
    lines = [
        "--!nocheck",
        "--!nolint",
        f"-- Generated by scripts/blender/geo_export.py from {name}. Edit the .blend, not this.",
        f'return {{ format = {data["format"]}, name = "{name}", unit = {data["unit"]!r}, parts = {{',
    ]
    for p in data["parts"]:
        lines.append(f'\t{{ name = "{p["name"]}", material = "{p["material"]}", verts = {p["verts"]}, tris = {p["tris"]},')
        for field in ("pos", "nrm", "col", "idx"):
            lines.append(f'\t\t{field} = "{p[field]}",')
        lines.append("\t},")
    lines.append("} }")
    return "\n".join(lines) + "\n"


def export(object_names, path, name=None, scale=3.571, origin=None):
    """Writes the module and returns a one-line summary. `origin` (Blender metres) becomes (0,0,0)."""
    import bmesh
    import bpy
    from pathlib import Path

    depsgraph = bpy.context.evaluated_depsgraph_get()
    ox, oy, oz = origin or (0.0, 0.0, 0.0)
    groups = {}
    for object_name in object_names:
        obj = bpy.data.objects[object_name]
        mesh = bpy.data.meshes.new_from_object(obj.evaluated_get(depsgraph), depsgraph=depsgraph)
        bm = bmesh.new()
        bm.from_mesh(mesh)
        bmesh.ops.triangulate(bm, faces=bm.faces[:])
        bm.to_mesh(mesh)
        bm.free()
        mesh.calc_loop_triangles()
        world = obj.matrix_world
        rotation = world.to_3x3()
        read_color = _color_reader(mesh)
        normals = mesh.corner_normals
        for tri in mesh.loop_triangles:
            material = mesh.materials[tri.material_index] if mesh.materials else None
            key = material.name if material else "Default"
            kind = (material.get("rbx_material") if material else None) or "SmoothPlastic"
            group = groups.setdefault(key, {"material": kind, "corners": []})
            base = _base_color(material)
            for loop_index, vertex_index in zip(tri.loops, tri.vertices):
                p = world @ mesh.vertices[vertex_index].co
                n = (rotation @ normals[loop_index].vector).normalized()
                rgb = base
                if read_color:
                    c = read_color(loop_index, vertex_index)
                    rgb = (c[0], c[1], c[2])
                group["corners"].append((
                    ((p.x - ox) * scale, (p.z - oz) * scale, -(p.y - oy) * scale),
                    (n.x, n.z, -n.y),
                    tuple(_srgb(v) for v in rgb),
                ))
        bpy.data.meshes.remove(mesh)
    data = pack(groups)
    name = name or object_names[0]
    text = to_luau(name, data)
    out = Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    tris = sum(p["tris"] for p in data["parts"])
    verts = sum(p["verts"] for p in data["parts"])
    return f"{name}: {len(data['parts'])} parts, {tris} tris, {verts} verts, {len(text) // 1024} KB -> {out}"
